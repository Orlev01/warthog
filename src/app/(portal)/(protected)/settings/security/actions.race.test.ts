// Adding a sign-in method versus recovery (sign-in audit, 14 November 2026). A session on a
// lost device passes its checks, then writes. If the owner's recovery evicts that session in
// between, the write is refused: a new passkey or recovery code is stored only while the
// session making it still exists (src/server/auth/sign-in-guard.ts).

import { test } from "node:test";
import assert from "node:assert/strict";

import { createSecurityActions } from "./actions";
import { createSession, lockAccountForEviction, recordStepUp, type Session } from "../../../../../server/auth/session";
import { evictLostFactors } from "../../../../../server/auth/recover-session";
import { issueRecoveryCode, verifyRecoveryCode } from "../../../../../server/auth/recovery";
import { createUser } from "../../../../../server/db/users";
import { withTransaction, type Db } from "../../../../../server/db/index";
import { systemRandom } from "../../../../../server/seams/random";
import { fixedClock } from "../../../../../server/seams/clock";
import { createAuthenticator } from "../../../../../test/authenticator";
import { freshDb } from "../../../../../test/db";

const clock = fixedClock(new Date("2026-11-14T00:00:00Z"));
const RP_ID = "warthog.com.au";

async function steppedUpSession(db: Db, userId: string): Promise<Session> {
  const created = await createSession(db, userId, { clock, random: systemRandom });
  return recordStepUp(db, created.session.id, { clock });
}

async function evict(db: Db, userId: string): Promise<void> {
  await withTransaction(db, async (tx) => {
    await lockAccountForEviction(tx, userId);
    await evictLostFactors(tx, userId, "the-new-passkey");
  });
}

async function owner(db: Db, label: string): Promise<string> {
  return (await createUser(db, { email: `${label}@example.test`, wrappedDek: "opaque" })).id;
}

test("a passkey added by a session recovery has just signed out isn't stored", async () => {
  const db = await freshDb();
  try {
    const userId = await owner(db, "add-passkey-race");
    const session = await steppedUpSession(db, userId);
    const actions = createSecurityActions({ db, clock, random: systemRandom, rpId: RP_ID });
    const begun = await actions.beginAddPasskey(session);
    if (!begun.ok) assert.fail("begin is allowed");
    const response = await createAuthenticator().register(begun.options);
    await evict(db, userId);

    assert.deepEqual(await actions.finishAddPasskey(session, response), { ok: false, reason: "signed_out" });
    assert.equal((await db.query("SELECT 1 FROM passkeys WHERE user_id = $1", [userId])).rows.length, 0);
  } finally {
    await db.close();
  }
});

test("a live session still adds its passkey", async () => {
  const db = await freshDb();
  try {
    const userId = await owner(db, "add-passkey-live");
    const session = await steppedUpSession(db, userId);
    const actions = createSecurityActions({ db, clock, random: systemRandom, rpId: RP_ID });
    const begun = await actions.beginAddPasskey(session);
    if (!begun.ok) assert.fail("begin is allowed");

    assert.deepEqual(await actions.finishAddPasskey(session, await createAuthenticator().register(begun.options)), { ok: true });
    assert.equal((await db.query("SELECT 1 FROM passkeys WHERE user_id = $1", [userId])).rows.length, 1);
  } finally {
    await db.close();
  }
});

test("a recovery code regenerated by a session recovery has just signed out isn't issued", async () => {
  const db = await freshDb();
  try {
    const userId = await owner(db, "regenerate-race");
    const session = await steppedUpSession(db, userId);
    // The code the recovery handed the owner.
    const { code } = await issueRecoveryCode(db, userId, { random: systemRandom });
    await evict(db, userId);
    const actions = createSecurityActions({ db, clock, random: systemRandom, rpId: RP_ID });

    assert.deepEqual(await actions.regenerateRecovery(session), { ok: false, reason: "signed_out" });
    assert.equal(await verifyRecoveryCode(db, userId, code), true, "the owner's code still works");
  } finally {
    await db.close();
  }
});
